// Builds data/world-110m.json: land and country-border paths for the impact map,
// pre-projected so the page needs no map library.
// Projection: equirectangular, centred on 155°E so the Pacific sits in the middle and the seam runs through the Atlantic (25°W)
// (the page uses the same maths in calendar.js: x = lon' * K, y = (LAT_TOP - lat) * K).
// Run: npm i d3-geo@3.1.1 topojson-client@3.1.0 world-atlas@2.0.2 && node tools/make-world.mjs
// Source: Natural Earth 1:110m (public domain) via world-atlas (ISC).
import {readFileSync, writeFileSync} from "node:fs";
import {createRequire} from "node:module";
import {geoEquirectangular, geoPath} from "d3-geo";
import {feature, mesh} from "topojson-client";
const require = createRequire(import.meta.url);
const W = 1000, K = W / 360, CENTER = 155, LAT_TOP = 75;
const proj = geoEquirectangular().rotate([-CENTER, 0]).scale(K * 180 / Math.PI).translate([W / 2, LAT_TOP * K]).precision(0.1);
const path = geoPath(proj).digits(1);
const land = require("world-atlas/land-110m.json");
const countries = require("world-atlas/countries-110m.json");
const out = {
  note: "Natural Earth 1:110m (public domain) via world-atlas. Equirectangular, centre 155°E, width 1000, top edge 75°N. Generated by tools/make-world.mjs.",
  width: W, center: CENTER, latTop: LAT_TOP, latBottom: -50,
  land: path(feature(land, land.objects.land)),
  borders: path(mesh(countries, countries.objects.countries, (a, b) => a !== b))
};
writeFileSync(new URL("../data/world-110m.json", import.meta.url), JSON.stringify(out));
console.log("land", out.land.length, "borders", out.borders.length);
